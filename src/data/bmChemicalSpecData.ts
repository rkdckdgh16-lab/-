/**
 * 실시간 검색 필터
 */
export function searchBmChemicalSpecDatabase(keyword: string): BmChemicalSpecItem[] {
  if (!keyword || keyword.trim() === '') {
    return BM_CHEMICAL_SPEC_LIST;
  }

  const query = keyword.toLowerCase().trim();

  return BM_CHEMICAL_SPEC_LIST.filter(item => {
    return (
      item.productName.toLowerCase().includes(query) ||
      item.modelSpec.toLowerCase().includes(query) ||
      item.no.toString() === query
    );
  });
}

function normalizeStr(str: string): string {
  return str
    .toLowerCase()
    .replace(/[\s\-_/\\(),.:;[\]{}'"+]+/g, '')
    .trim();
}

/**
 * 품명/모델명으로 BM-화학물질명세내역 매칭 점수 계산
 */
export function scoreBmChemicalSpecItem(item: BmChemicalSpecItem, searchItemName: string): number {
  if (!searchItemName) return 0;

  const itemLower = searchItemName.toLowerCase().trim();
  const prodLower = item.productName.toLowerCase().trim();
  const specLower = item.modelSpec ? item.modelSpec.toLowerCase().trim() : '';

  const normSearch = normalizeStr(searchItemName);
  const normProd = normalizeStr(item.productName);
  const normSpec = normalizeStr(item.modelSpec || '');

  let score = 0;

  // 1. Exact match
  if (itemLower === prodLower || (specLower && itemLower === specLower)) {
    return 1000;
  }
  if (normSearch && (normSearch === normProd || (normSpec && normSearch === normSpec))) {
    return 950;
  }

  // 2. Contains match
  if (itemLower.includes(prodLower) || prodLower.includes(itemLower)) {
    score += 300;
  }
  if (specLower && (itemLower.includes(specLower) || specLower.includes(itemLower))) {
    score += 250;
  }
  if (normSearch && normProd && (normSearch.includes(normProd) || normProd.includes(normSearch))) {
    score += 200;
  }

  // 3. Korean/English aliases
  const aliases: Record<string, string[]> = {
    'lfp': ['lithium iron phosphate', '인산철', 'lfp', '나노원 lfp', 'ecocath'],
    'ncm': ['nickel cobalt manganese', 'p-ncm', 'ncm', 'ncmo'],
    'nca': ['nickel cobalt aluminum', 'p-nca', 'nca', 'ncao'],
    'nc': ['nickel cobalt', 'p-nc', 'nickelcobalt'],
    'nm': ['nickel manganese', 'nm', 'nma', 'nmao'],
    'lmfp': ['lithium manganese iron phosphate', 'lmfp', 'lmfp64', 'dy-19'],
    'niobium': ['니오븀', 'niobium pentoxide'],
    'diiron': ['인화철', 'diiron phosphide'],
    'kuranode': ['kuranode', '쿠라노드', '음극재'],
    'carbon': ['경질 카본', 'bshc', 'carbon'],
    'nfpp': ['인산피로인산철나트륨', 'nfpp']
  };

  for (const [key, aliasList] of Object.entries(aliases)) {
    const searchHas = aliasList.some(a => itemLower.includes(a) || normSearch.includes(normalizeStr(a)));
    const itemHas = aliasList.some(a => prodLower.includes(a) || (specLower && specLower.includes(a)) || normProd.includes(normalizeStr(a)));
    if (searchHas && itemHas) {
      score += 220;
    }
  }

  // 4. Token overlap
  const tokens = itemLower.split(/[\s,()_\-/+]+/g).filter(t => t.length >= 2);
  if (tokens.length > 0) {
    const matchedTokens = tokens.filter(tok => 
      prodLower.includes(tok) || (specLower && specLower.includes(tok))
    );
    const ratio = matchedTokens.length / tokens.length;
    if (ratio >= 0.8) score += 200;
    else if (ratio >= 0.5) score += 100;
  }

  return score;
}

/**
 * 품명으로 BM-화학물질명세내역 매칭 항목 검색
 */
export function matchBmChemicalSpec(itemName: string): BmChemicalSpecItem[] {
  if (!itemName || itemName.trim() === '') return [];

  const MATCH_THRESHOLD = 180;
  const scored = BM_CHEMICAL_SPEC_LIST
    .map(item => ({ item, score: scoreBmChemicalSpecItem(item, itemName) }))
    .filter(res => res.score >= MATCH_THRESHOLD)
    .sort((a, b) => b.score - a.score);

  if (scored.length === 0) return [];
  // Return top matches (up to 3)
  return scored.slice(0, 3).map(s => s.item);
}
